from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

notes = [p for p in open("cn.txt").read().split("\n\n") if p.strip()]
vec = TfidfVectorizer().fit(notes)
note_vecs = vec.transform(notes)

def retrieve(question, k=2):
    scores = cosine_similarity(vec.transform([question]), note_vecs)[0]
    return [notes[i] for i in scores.argsort()[::-1][:k]]

retrieve("what is vci",6)

retrieve("what is  Hamming Distance")

def rag(question):
    context = "\n---\n".join(retrieve(question))
    return ask(
        f"Answer using ONLY this context. If the answer is not there, "
        f"say you do not know.\n\nContext:\n{context}\n\nQuestion: {question}"
    )

rag("what is ai")

rag("What is Datagram Networks")

